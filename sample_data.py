def generate_ma_code_0000(model):
    """Generate MA code 0000 data with random values for all fields except code.
    Code is always 0000, but fat/snf/rate/amt/qty have realistic random values."""
    milk_types_receipt = ["Mix", "Cow", "Buffalo"]
    milk_types_stipl = ["MIX", "COW", "BUF"]
    shifts = ["M", "E"]

    qty = round(random.uniform(1.5, 18.0), 2)
    fat = round(random.uniform(3.5, 7.5), 2)
    snf = round(random.uniform(8.0, 9.5), 1)
    rate = round(random.uniform(40.0, 55.0), 2)
    amt = round(qty * rate, 2)
    clr = round(random.uniform(25.0, 35.0), 1)
    shift = random.choice(shifts)
    counter = random.randint(1, 10)

    # 1004 EKOmilk Ultra V1 - simpler receipt
    if model == 1004:
        mt = random.choice(milk_types_receipt)
        return (
            f"Provisional Acknowldgement Slip\n\n"
            f"    Benny Impex Private Limited\n"
            f"        New Delhi\n\n"
            f"Date: 05/12/23        Time: 07:01\n"
            f"Code:........\n"
            f"Milk Type: {mt}    Quantity:........\n"
            f"FAT:      {round(fat, 1):.1f}    SNF:    {snf:.1f}%\n"
            f"Rate(Rs.):........Amount:........"
        )

    # 2001 Kurien UltraScan - raw analyzer
    elif model == 2001:
        temp = round(random.uniform(30.0, 32.0), 1)
        protein = round(random.uniform(2.8, 3.5), 1)
        lactose = round(random.uniform(4.5, 5.3), 1)
        fp = round(random.uniform(-0.68, -0.52), 3)
        ph = round(random.uniform(6.4, 6.8), 1)
        cond = round(random.uniform(3.9, 4.4), 1)
        density = round(random.uniform(29.0, 31.0), 1)
        return (
            f"Milk Analyzer\n"
            f"SN: 38344  Mode:    2\n"
            f"    Temp. {temp:.1f} C\n"
            f"Fat.............. {round(fat, 1):.1f}%\n"
            f"SNF.............. {snf:.1f}%\n"
            f"Density..........{density:.1f}\n"
            f"Protein.......... {protein:.1f}%\n"
            f"Lactose.......... {lactose:.1f}%\n"
            f"Salts............ 0.7%\n"
            f"Added water...... 0.0%\n"
            f"Freezing point..{fp:+.3f} C\n"
            f"pH............... {ph:.1f}\n"
            f"Conductivity..... {cond:.1f}\n"
            f"07:01    05/12/23"
        )

    # 2002 REIL Electronic - simple raw number
    elif model == 2002:
        return f"{round(fat, 2):.2f}"

    # 2004 Essae - # prefix with freezing point
    elif model == 2004:
        protein = round(random.uniform(2.8, 3.5), 2)
        salts = round(random.uniform(0.60, 0.74), 2)
        lactose = round(random.uniform(4.3, 5.2), 2)
        density = round(random.uniform(28.0, 31.0), 2)
        fp = round(random.uniform(-0.68, -0.52), 3)
        weight = round(random.uniform(400.0, 750.0), 1)
        return _fmt_2004(round(fat, 2), snf, clr, protein, salts, lactose, density, 0.00, fp, 2, "23098128", weight)

    # 2005 Lactoscan - simple two values
    elif model == 2005:
        v1 = round(random.uniform(3.5, 13.5), 2)
        v2 = round(random.uniform(5.0, 9.5), 2)
        return f"#{v1:05.2f} {v2:05.2f}"

    # 2003 Lactosure - pipe-separated raw
    elif model == 2003:
        temp = round(random.uniform(27.0, 29.0), 2)
        protein = round(random.uniform(2.8, 3.5), 2)
        lactose = round(random.uniform(4.3, 5.2), 2)
        le = round(random.uniform(3.3, 4.5), 2)
        return _fmt_2003(le, "A", 1, round(fat, 2), snf, clr, protein, lactose, 0.70, 0.00, temp)

    # Receipt format (models 1001-1003, 2004)
    elif 1001 <= model <= 2004:
        mt = random.choice(milk_types_receipt)
        return (
            f"Provisional Acknowldgement Slip\n\n"
            f"DIARY CRAFT PVT LTD\n\n"
            f"PEERNAGAR\n\n"
            f"MCC Code: MCC_001\n"
            f"VLCC Code: 00000215\n"
            f"Date: 05/12/23          Time: 07:01\n"
            f"Code: 0000\n"
            f"Name:\n"
            f"Milk Type: {mt}    Quantity: {qty:.2f}\n"
            f"FAT:      {fat:.2f}%   SNF:      {snf:.1f}%\n"
            f"Rate (Rs.): {rate:.2f}\n"
            f"Amount: {amt:.2f}\n"
            f"CLR: {clr:.1f}\n"
            f"Shift: {shift}    SSCounter: {counter}"
        )

    # 3003 IndiZ - shorter parentheses format
    elif model == 3003:
        return _fmt_3003(round(fat, 2), snf, clr, round(random.uniform(16.0, 22.0), 2), 0.00)

    # Parentheses format (models 3001-3002, 3004)
    elif 3001 <= model <= 3004:
        # Format: (FFFSSSRRR...) - randomize values but code portion = 0000
        f_int = int(fat * 100)
        s_int = int(snf * 100)
        q_int = int(qty * 100)
        r_int = int(rate * 100)
        a_int = int(amt)
        return f"({f_int:04d}{s_int:04d}{r_int:04d}{q_int:04d}{clr*10:04.0f}{a_int:05d}0000{counter:03d}{shift})"

    # Newline format (models 4001-4003)
    elif 4001 <= model <= 4003:
        fat1 = round(random.uniform(3.0, 5.0), 2)
        snf1 = round(random.uniform(8.5, 9.5), 2)
